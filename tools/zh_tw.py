MAP = {}
for pair in TERMS + AMBIGUOUS + EXTRA:
    a, b = pair.split('=')
    MAP[a] = chars(b) if a in ('文件夹', '费里') else b
PATTERN = re.compile('|'.join(sorted(map(re.escape, MAP), key=len, reverse=True)))
PROTECT = re.compile(r'(\{[^{}]*\}|\[[^\]]*\]|<[^<>]*>)')  # Platzhalter und Tags unverändert


def convert(s):
    out = []
    for i, part in enumerate(PROTECT.split(s)):
        if i % 2:
            out.append(part)
            continue
        pos = 0
        for m in PATTERN.finditer(part):
            out.append(chars(part[pos:m.start()]) + MAP[m.group()])
            pos = m.end()
        out.append(chars(part[pos:]))
    return ''.join(out).replace('“', '「').replace('”', '」').replace('‘', '『').replace('’', '』')


