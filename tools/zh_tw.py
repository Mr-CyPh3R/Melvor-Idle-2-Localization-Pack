import ctypes, glob, json, os, re

_k32 = ctypes.windll.kernel32
LCMAP_TRADITIONAL_CHINESE = 0x04000000


def chars(s):
    n = _k32.LCMapStringEx('zh-TW', LCMAP_TRADITIONAL_CHINESE, s, len(s), None, 0, None, None, 0)
    b = ctypes.create_unicode_buffer(n + 1)
    _k32.LCMapStringEx('zh-TW', LCMAP_TRADITIONAL_CHINESE, s, len(s), b, n, None, None, 0)
    return b.value


